const fill = (s: string, v?: Record<string, unknown>) => v ? s.replace(/\{(\w+)\}/g, (m, k: string) => k in v ? String(v[k] ?? '') : m) : s;
/** t() 와 같다. 언어 파일에 아직 없는 call.* 키는 위 한국어로 */
export const tt = (key: string, v?: Record<string, unknown>) => has(key) ? t(key, v) : fill(KO[key] ?? '', v);
